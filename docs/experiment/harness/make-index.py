#!/usr/bin/env python3
"""Build docs/experiment/run-index.md: every run with its arm, answer sheet, cost and links.

The index is UNBLINDED (it shows which arm made each run). Don't show it to anyone scoring.
"""
import json
import os

H = os.path.dirname(os.path.abspath(__file__))
RUNS = os.path.join(H, "runs")
OUT = os.path.join(H, "..", "run-index.md")
ARM_NAMES = {"0": "0: Prompt + plan", "A": "A: No architecture", "B": "B: Architecture, no fence", "C": "C: Architecture, fenced"}

sealed = json.load(open(os.path.join(RUNS, "sealed.json")))
rows = []
for rid, s in sealed.items():
    mpath = os.path.join(RUNS, rid, "private", "manifest.json")
    if not os.path.exists(mpath):
        continue
    m = json.load(open(mpath))
    cost = sum((st.get("total_cost_usd") or 0) for st in m["stages"].values())
    mins = sum((st.get("duration_ms") or 0) for st in m["stages"].values()) / 60000
    sheet = m.get("answer_sheet") or s.get("answer_sheet") or f"{s['feature']}-pm-oracle.md"
    files = []
    for f in ("qa.md", "spec.md", "tickets.md", "plan.md"):
        if os.path.exists(os.path.join(RUNS, rid, "output", f)):
            files.append(f"[{f.removesuffix('.md')}](harness/runs/{rid}/output/{f})")
    scoring = os.path.join(RUNS, rid, "scoring")
    if os.path.isdir(scoring):
        for f in sorted(os.listdir(scoring)):
            files.append(f"[{f.removesuffix('.md')}](harness/runs/{rid}/scoring/{f})")
    rows.append((s["feature"], sheet, m["started"], s["arm"], rid, cost, mins, files))

rows.sort(key=lambda r: (r[0] != "pilot", r[1], r[2][:13], r[3]))
lines = [
    "# Run index",
    "",
    "*Generated by `harness/make-index.py`. **Unblinded:** it shows which arm made each run. "
    "Don't share it with anyone scoring.*",
    "",
    "For each run: **qa** is the decision log (the agent's questions and the stand-in PM's answers), "
    "**spec** and **tickets** (or **plan**) are what the agent wrote, and **intent-diff** or "
    "**decision-inventory** is the blind scorer's report.",
    "",
]
group = None
for feat, sheet, started, arm, rid, cost, mins, files in rows:
    g = (feat, sheet)
    if g != group:
        group = g
        lines += ["", f"## {feat.capitalize()} feature · answer sheet `{sheet}`", "",
                  "| Arm | Run | Started (UTC) | Time | Cost | Files |", "|---|---|---|---|---|---|"]
    lines.append(f"| {ARM_NAMES.get(arm, arm)} | `{rid}` | {started[:16].replace('T', ' ')} | {mins:.1f} min | ${cost:.2f} | {' · '.join(files)} |")
open(OUT, "w").write("\n".join(lines) + "\n")
print(f"wrote {os.path.normpath(OUT)} ({len(rows)} runs)")
